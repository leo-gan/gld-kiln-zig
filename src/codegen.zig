//! Emit Zig structs from the JSON Schema subset.

const std = @import("std");
const Error = @import("error.zig").Error;
const Schema = @import("schema.zig").Schema;
const Kind = @import("schema.zig").Kind;
const schemaFromJson = @import("schema_json.zig").schemaFromJson;

pub fn emit(gpa: std.mem.Allocator, text: []const u8) (Error || std.Io.Writer.Error)![]u8 {
    var arena_state = std.heap.ArenaAllocator.init(gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const parsed = try schemaFromJson(arena, text);
    if (parsed.root.kind != .structure) return error.SCHEMA;
    var structs: std.ArrayList(*const Schema) = .empty;
    try collect(arena, parsed.root, &structs);
    var out: std.Io.Writer.Allocating = .init(gpa);
    errdefer out.deinit();
    const w = &out.writer;
    try w.writeAll(
        \\//! Generated by gld-kilngen-zig. Do not edit.
        \\
        \\const std = @import("std");
        \\const kiln = @import("kiln");
        \\
        \\
    );
    for (structs.items) |schema| {
        const hint = try std.fmt.allocPrint(arena, "{s}Field", .{schema.label});
        try emitPairs(w, arena, schema, hint);
        try emitStruct(w, arena, schema);
    }
    return out.toOwnedSlice();
}

fn collect(arena: std.mem.Allocator, schema: *const Schema, out: *std.ArrayList(*const Schema)) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .list, .opt, .dict => try collect(arena, schema.child.?, out),
        .structure => {
            for (schema.fields) |field| try collect(arena, field.schema, out);
            for (out.items) |seen| if (seen == schema) return;
            try out.append(arena, schema);
        },
        else => {},
    }
}

fn emitStruct(w: *std.Io.Writer, arena: std.mem.Allocator, schema: *const Schema) (Error || std.Io.Writer.Error)!void {
    if (!ident(schema.label)) return error.SCHEMA;
    try w.print("pub const {s} = struct {{\n", .{schema.label});
    for (schema.fields) |field| {
        if (!ident(field.name)) return error.SCHEMA;
        const hint = try fieldHint(arena, schema.label, field.name);
        try w.print("    {s}: ", .{field.name});
        try writeType(w, field.schema, hint);
        try w.writeAll(" = ");
        try writeDefault(w, field.schema);
        try w.writeAll(",\n");
    }
    try w.print(
        \\
        \\    pub fn encode(self: {s}, gpa: std.mem.Allocator) kiln.Error![]u8 {{
        \\        var writer = kiln.Writer{{}};
        \\        errdefer writer.deinit(gpa);
        \\        try self.encodeTo(&writer, gpa);
        \\        return writer.toOwned(gpa);
        \\    }}
        \\
        \\    pub fn encodeTo(self: {s}, writer: *kiln.Writer, gpa: std.mem.Allocator) kiln.Error!void {{
        \\        try writer.descend();
        \\        defer writer.ascend();
        \\
    , .{ schema.label, schema.label });
    if (schema.fields.len == 0) try w.writeAll("        _ = gpa;\n");
    for (schema.fields) |field| {
        const hint = try fieldHint(arena, schema.label, field.name);
        const expr = try std.fmt.allocPrint(arena, "self.{s}", .{field.name});
        try writeEncode(w, arena, "        ", expr, field.schema, hint);
    }
    try w.writeAll(
        \\    }
        \\
        \\    pub fn decode(gpa: std.mem.Allocator, buf: []const u8) kiln.Error!
    );
    try w.print("{s} {{\n", .{schema.label});
    try w.writeAll(
        \\        var reader = kiln.Reader.init(buf, .{});
        \\        const value = try read(&reader, gpa);
        \\        errdefer {
        \\            var doomed = value;
        \\            doomed.deinit(gpa);
        \\        }
        \\        try reader.finish();
        \\        return value;
        \\    }
        \\
        \\    pub fn read(reader: *kiln.Reader, gpa: std.mem.Allocator) kiln.Error!
    );
    try w.print("{s} {{\n", .{schema.label});
    try w.writeAll(
        \\        try reader.descend();
        \\        defer reader.ascend();
        \\        var self = 
    );
    try w.print("{s}{{}};\n", .{schema.label});
    try w.writeAll("        errdefer self.deinit(gpa);\n");
    for (schema.fields) |field| {
        const hint = try fieldHint(arena, schema.label, field.name);
        const dest = try std.fmt.allocPrint(arena, "self.{s}", .{field.name});
        try writeRead(w, arena, "        ", dest, field.schema, hint);
    }
    try w.writeAll("        return self;\n    }\n\n");
    try w.print("    pub fn encodedSize(self: {s}) usize {{\n        var n: usize = 0;\n", .{schema.label});
    for (schema.fields) |field| {
        const hint = try fieldHint(arena, schema.label, field.name);
        const expr = try std.fmt.allocPrint(arena, "self.{s}", .{field.name});
        try writeSize(w, arena, "        ", expr, field.schema, hint);
    }
    try w.writeAll("        return n;\n    }\n\n    pub fn deinit(self: *");
    try w.print("{s}, gpa: std.mem.Allocator) void {{\n", .{schema.label});
    var any = false;
    for (schema.fields) |field| if (owns(field.schema)) {
        any = true;
        const hint = try fieldHint(arena, schema.label, field.name);
        try writeDeinit(w, "        ", "self", field.name, field.schema, hint);
    };
    if (!any) try w.writeAll("        _ = self;\n        _ = gpa;\n");
    try w.writeAll("    }\n};\n\n");
}

fn emitPairs(w: *std.Io.Writer, arena: std.mem.Allocator, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .list, .opt => try emitPairs(w, arena, schema.child.?, hint),
        .dict => {
            const inner = try std.fmt.allocPrint(arena, "{s}V", .{hint});
            try emitPairs(w, arena, schema.child.?, inner);
            try w.print("pub const {s} = struct {{\n    key: []const u8 = \"\",\n    value: ", .{hint});
            try writeType(w, schema.child.?, inner);
            try w.writeAll(" = ");
            try writeDefault(w, schema.child.?);
            try w.writeAll(",\n};\n\n");
        },
        .structure => for (schema.fields) |field| {
            const hint_field = try fieldHint(arena, schema.label, field.name);
            try emitFieldPairs(w, arena, field.schema, hint_field);
        },
        else => {},
    }
}

fn emitFieldPairs(w: *std.Io.Writer, arena: std.mem.Allocator, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .structure => {},
        .list, .opt => try emitFieldPairs(w, arena, schema.child.?, hint),
        .dict => {
            const inner = try std.fmt.allocPrint(arena, "{s}V", .{hint});
            try emitFieldPairs(w, arena, schema.child.?, inner);
            try w.print("pub const {s} = struct {{\n    key: []const u8 = \"\",\n    value: ", .{hint});
            try writeType(w, schema.child.?, inner);
            try w.writeAll(" = ");
            try writeDefault(w, schema.child.?);
            try w.writeAll(",\n};\n\n");
        },
        else => {},
    }
}

fn fieldHint(arena: std.mem.Allocator, parent: []const u8, name: []const u8) Error![]u8 {
    return std.fmt.allocPrint(arena, "{s}_{s}Pair", .{ parent, name });
}

fn writeType(w: *std.Io.Writer, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .boolean => try w.writeAll("bool"),
        .i8 => try w.writeAll("i8"),
        .i16 => try w.writeAll("i16"),
        .i32 => try w.writeAll("i32"),
        .i64, .int => try w.writeAll("i64"),
        .u8 => try w.writeAll("u8"),
        .u16 => try w.writeAll("u16"),
        .u32 => try w.writeAll("u32"),
        .u64, .uint => try w.writeAll("u64"),
        .f32 => try w.writeAll("f32"),
        .f64 => try w.writeAll("f64"),
        .str, .bytes => try w.writeAll("[]const u8"),
        .tensors => return error.SCHEMA,
        .structure => try w.writeAll(schema.label),
        .list => {
            try w.writeAll("[]const ");
            try writeType(w, schema.child.?, hint);
        },
        .opt => {
            try w.writeAll("?");
            try writeType(w, schema.child.?, hint);
        },
        .dict => try w.print("[]const {s}", .{hint}),
    }
}

fn writeDefault(w: *std.Io.Writer, schema: *const Schema) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .boolean => try w.writeAll("false"),
        .str => try w.writeAll("\"\""),
        .bytes, .list, .dict => try w.writeAll("&.{}"),
        .opt => try w.writeAll("null"),
        .structure => try w.writeAll(".{}"),
        .f32, .f64 => try w.writeAll("0"),
        else => try w.writeAll("0"),
    }
}

fn writeEncode(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, expr: []const u8, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .boolean => try w.print("{s}try writer.boolean(gpa, {s});\n", .{ indent, expr }),
        .f32 => try w.print("{s}try writer.float32(gpa, {s});\n", .{ indent, expr }),
        .f64 => try w.print("{s}try writer.float64(gpa, {s});\n", .{ indent, expr }),
        .i8, .i16, .i32, .i64, .int, .u8, .u16, .u32, .u64, .uint => {
            try w.print("{s}try writer.int(gpa, {s}, {s});\n", .{ indent, zigScalar(schema.kind), expr });
        },
        .str => try w.print("{s}try writer.str(gpa, {s});\n", .{ indent, expr }),
        .bytes => try w.print("{s}try writer.bytes(gpa, {s});\n", .{ indent, expr }),
        .structure => try w.print("{s}try {s}.encodeTo(writer, gpa);\n", .{ indent, expr }),
        .tensors => return error.SCHEMA,
        .opt => {
            try w.print("{s}if ({s}) |held| {{\n", .{ indent, expr });
            const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
            try w.print("{s}try writer.int(gpa, u8, 1);\n", .{nested});
            try writeEncode(w, arena, nested, "held", schema.child.?, hint);
            try w.print("{s}}} else try writer.int(gpa, u8, 0);\n", .{indent});
        },
        .list => try writeListEncode(w, arena, indent, expr, schema.child.?, hint),
        .dict => try writeDictEncode(w, arena, indent, expr, schema.child.?, hint),
    }
}

fn writeListEncode(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, expr: []const u8, elem: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    if (elem.kind == .u8) {
        try w.print("{s}try writer.bytes(gpa, {s});\n", .{ indent, expr });
        return;
    }
    try w.print("{s}if ({s}.len > writer.cap or {s}.len > std.math.maxInt(u32)) return error.LIMIT;\n", .{ indent, expr, expr });
    try w.print("{s}try writer.int(gpa, u32, @intCast({s}.len));\n", .{ indent, expr });
    if (elem.kind == .f32) {
        try w.print("{s}try writer.float32s(gpa, {s});\n", .{ indent, expr });
        return;
    }
    if (elem.kind == .f64) {
        try w.print("{s}try writer.float64s(gpa, {s});\n", .{ indent, expr });
        return;
    }
    if (width(elem.kind) != null and elem.kind != .boolean) {
        try w.print("{s}try writer.pod(gpa, {s}, {s});\n", .{ indent, zigScalar(elem.kind), expr });
        return;
    }
    const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
    try w.print("{s}for ({s}) |item| {{\n", .{ indent, expr });
    try writeEncode(w, arena, nested, "item", elem, hint);
    try w.print("{s}}}\n", .{indent});
}

fn writeDictEncode(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, expr: []const u8, elem: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
    try w.print("{s}if ({s}.len > writer.cap or {s}.len > std.math.maxInt(u32)) return error.LIMIT;\n", .{ indent, expr, expr });
    try w.print("{s}const order = try gpa.alloc(usize, {s}.len);\n", .{ indent, expr });
    try w.print("{s}defer gpa.free(order);\n", .{indent});
    try w.print("{s}for (order, 0..) |*slot, i| slot.* = i;\n", .{indent});
    try w.print("{s}std.sort.pdq(usize, order, {s}, struct {{\n", .{ indent, expr });
    try w.print("{s}    fn less(items: []const {s}, a: usize, b: usize) bool {{\n", .{ indent, hint });
    try w.print("{s}        return std.mem.order(u8, items[a].key, items[b].key) == .lt;\n", .{indent});
    try w.print("{s}    }}\n{s}}}.less);\n", .{ indent, indent });
    try w.print("{s}try writer.int(gpa, u32, @intCast({s}.len));\n", .{ indent, expr });
    try w.print("{s}for (order) |index| {{\n", .{indent});
    try w.print("{s}try writer.str(gpa, {s}[index].key);\n", .{ nested, expr });
    const value_expr = try std.fmt.allocPrint(arena, "{s}[index].value", .{expr});
    try writeEncode(w, arena, nested, value_expr, elem, try std.fmt.allocPrint(arena, "{s}V", .{hint}));
    try w.print("{s}}}\n", .{indent});
}

fn writeRead(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, dest: []const u8, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    if (try writeSimpleRead(w, indent, dest, schema)) return;
    switch (schema.kind) {
        .opt => {
            try w.print("{s}{s} = held: {{\n", .{ indent, dest });
            const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
            try w.print("{s}try reader.descend();\n{s}defer reader.ascend();\n", .{ nested, nested });
            try w.print("{s}if (!try reader.optTag()) break :held null;\n", .{nested});
            if (simpleExpr(schema.child.?)) |text| {
                try w.print("{s}break :held {s};\n", .{ nested, text });
            } else if (schema.child.?.kind == .structure) {
                try w.print("{s}break :held try {s}.read(reader, gpa);\n", .{ nested, schema.child.?.label });
            } else {
                try w.print("{s}var inner: ", .{nested});
                try writeType(w, schema.child.?, hint);
                try w.writeAll(" = undefined;\n");
                try writeRead(w, arena, nested, "inner", schema.child.?, hint);
                try w.print("{s}break :held inner;\n", .{nested});
            }
            try w.print("{s}}};\n", .{indent});
        },
        .list => try writeListRead(w, arena, indent, dest, schema.child.?, hint),
        .dict => try writeDictRead(w, arena, indent, dest, schema.child.?, hint),
        .structure => try w.print("{s}{s} = try {s}.read(reader, gpa);\n", .{ indent, dest, schema.label }),
        else => return error.SCHEMA,
    }
}

fn writeSimpleRead(w: *std.Io.Writer, indent: []const u8, dest: []const u8, schema: *const Schema) (Error || std.Io.Writer.Error)!bool {
    const text = simpleExpr(schema) orelse return false;
    try w.print("{s}{s} = {s};\n", .{ indent, dest, text });
    return true;
}

fn simpleExpr(schema: *const Schema) ?[]const u8 {
    return switch (schema.kind) {
        .boolean => "try reader.boolean()",
        .i8 => "try reader.int(i8)",
        .i16 => "try reader.int(i16)",
        .i32 => "try reader.int(i32)",
        .i64, .int => "try reader.int(i64)",
        .u8 => "try reader.int(u8)",
        .u16 => "try reader.int(u16)",
        .u32 => "try reader.int(u32)",
        .u64, .uint => "try reader.int(u64)",
        .f32 => "try reader.float32()",
        .f64 => "try reader.float64()",
        .str => "try reader.str()",
        .bytes => "try reader.bytes()",
        .list => if (schema.child.?.kind == .u8) "try reader.bytes()" else null,
        else => null,
    };
}

fn writeListRead(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, dest: []const u8, elem: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
    try w.print("{s}{s} = items: {{\n", .{ indent, dest });
    try w.print("{s}try reader.descend();\n{s}defer reader.ascend();\n", .{ nested, nested });
    try w.print("{s}const count = try reader.listHeader({d});\n", .{ nested, minWire(elem) });
    try w.writeAll(nested);
    try w.writeAll("const items = try gpa.alloc(");
    try writeType(w, elem, hint);
    try w.writeAll(", count);\n");
    try w.print("{s}errdefer gpa.free(items);\n", .{nested});
    if (elem.kind == .f32) {
        try w.print("{s}try reader.float32s(items);\n", .{nested});
    } else if (elem.kind == .f64) {
        try w.print("{s}try reader.float64s(items);\n", .{nested});
    } else if (width(elem.kind) != null and elem.kind != .boolean) {
        try w.print("{s}try reader.pod({s}, items);\n", .{ nested, zigScalar(elem.kind) });
    } else {
        try w.print("{s}for (items) |*item| {{\n", .{nested});
        const body = try std.fmt.allocPrint(arena, "{s}    ", .{nested});
        if (simpleExpr(elem)) |text| {
            try w.print("{s}item.* = {s};\n", .{ body, text });
        } else if (elem.kind == .structure) {
            try w.print("{s}item.* = try {s}.read(reader, gpa);\n", .{ body, elem.label });
        } else {
            try writeRead(w, arena, body, "item.*", elem, hint);
        }
        try w.print("{s}}}\n", .{nested});
    }
    try w.print("{s}break :items items;\n{s}}};\n", .{ nested, indent });
}

fn writeDictRead(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, dest: []const u8, elem: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
    const body = try std.fmt.allocPrint(arena, "{s}    ", .{nested});
    try w.print("{s}{s} = items: {{\n", .{ indent, dest });
    try w.print("{s}try reader.descend();\n{s}defer reader.ascend();\n", .{ nested, nested });
    try w.print("{s}const count = try reader.listHeader(4);\n", .{nested});
    try w.print("{s}const items = try gpa.alloc({s}, count);\n", .{ nested, hint });
    try w.print("{s}errdefer gpa.free(items);\n", .{nested});
    try w.print("{s}var prev: []const u8 = \"\";\n{s}var seen_key = false;\n", .{ nested, nested });
    try w.print("{s}for (items) |*item| {{\n", .{nested});
    try w.print("{s}const key = try reader.str();\n", .{body});
    try w.print("{s}if (seen_key and std.mem.order(u8, key, prev) == .lt) return error.TYPE;\n", .{body});
    try w.print("{s}seen_key = true;\n{s}prev = key;\n", .{ body, body });
    try w.print("{s}item.key = key;\n", .{body});
    const inner = try std.fmt.allocPrint(arena, "{s}V", .{hint});
    if (simpleExpr(elem)) |text| {
        try w.print("{s}item.value = {s};\n", .{ body, text });
    } else if (elem.kind == .structure) {
        try w.print("{s}item.value = try {s}.read(reader, gpa);\n", .{ body, elem.label });
    } else try writeRead(w, arena, body, "item.value", elem, inner);
    try w.print("{s}}}\n{s}break :items items;\n{s}}};\n", .{ nested, nested, indent });
}

fn writeSize(w: *std.Io.Writer, arena: std.mem.Allocator, indent: []const u8, expr: []const u8, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    switch (schema.kind) {
        .boolean, .i8, .u8 => try w.print("{s}n += 1;\n", .{indent}),
        .i16, .u16 => try w.print("{s}n += 2;\n", .{indent}),
        .i32, .u32, .f32 => try w.print("{s}n += 4;\n", .{indent}),
        .i64, .u64, .int, .uint, .f64 => try w.print("{s}n += 8;\n", .{indent}),
        .str, .bytes => try w.print("{s}n += 4 + {s}.len;\n", .{ indent, expr }),
        .structure => try w.print("{s}n += {s}.encodedSize();\n", .{ indent, expr }),
        .tensors => return error.SCHEMA,
        .opt => {
            const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
            try w.print("{s}if ({s}) |held| {{\n{s}n += 1;\n", .{ indent, expr, nested });
            try writeSize(w, arena, nested, "held", schema.child.?, hint);
            try w.print("{s}}} else n += 1;\n", .{indent});
        },
        .list => {
            if (schema.child.?.kind == .u8) {
                try w.print("{s}n += 4 + {s}.len;\n", .{ indent, expr });
                return;
            }
            if (width(schema.child.?.kind)) |bytes| {
                try w.print("{s}n += 4 + {s}.len * {d};\n", .{ indent, expr, bytes });
                return;
            }
            const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
            try w.print("{s}n += 4;\n{s}for ({s}) |item| {{\n", .{ indent, indent, expr });
            try writeSize(w, arena, nested, "item", schema.child.?, hint);
            try w.print("{s}}}\n", .{indent});
        },
        .dict => {
            const nested = try std.fmt.allocPrint(arena, "{s}    ", .{indent});
            try w.print("{s}n += 4;\n{s}for ({s}) |pair| {{\n{s}n += 4 + pair.key.len;\n", .{ indent, indent, expr, nested });
            try writeSize(w, arena, nested, "pair.value", schema.child.?, hint);
            try w.print("{s}}}\n", .{indent});
        },
    }
}

fn writeDeinit(w: *std.Io.Writer, indent: []const u8, parent: []const u8, name: []const u8, schema: *const Schema, hint: []const u8) (Error || std.Io.Writer.Error)!void {
    _ = hint;
    switch (schema.kind) {
        .list => {
            if (owns(schema.child.?)) {
                try w.print("{s}for ({s}.{s}) |item| {{\n", .{ indent, parent, name });
                try w.print("{s}    var copy = item;\n{s}    copy.deinit(gpa);\n{s}}}\n", .{ indent, indent, indent });
            }
            try w.print("{s}gpa.free({s}.{s});\n", .{ indent, parent, name });
        },
        .dict => {
            if (owns(schema.child.?)) {
                try w.print("{s}for ({s}.{s}) |item| {{\n", .{ indent, parent, name });
                try w.print("{s}    var copy = item.value;\n{s}    copy.deinit(gpa);\n{s}}}\n", .{ indent, indent, indent });
            }
            try w.print("{s}gpa.free({s}.{s});\n", .{ indent, parent, name });
        },
        .opt => {
            const child = schema.child.?;
            try w.print("{s}if ({s}.{s}) |held| {{\n", .{ indent, parent, name });
            if (child.kind == .list or child.kind == .dict) {
                if (owns(child.child.?)) {
                    const value = if (child.kind == .dict) "item.value" else "item";
                    try w.print("{s}    for (held) |item| {{\n{s}        var copy = {s};\n{s}        copy.deinit(gpa);\n{s}    }}\n", .{ indent, indent, value, indent, indent });
                }
                try w.print("{s}    gpa.free(held);\n", .{indent});
            } else if (child.kind == .structure or owns(child)) {
                try w.print("{s}    var copy = held;\n{s}    copy.deinit(gpa);\n", .{ indent, indent });
            }
            try w.print("{s}}}\n", .{indent});
        },
        .structure => try w.print("{s}{s}.{s}.deinit(gpa);\n", .{ indent, parent, name }),
        else => {},
    }
}

fn owns(schema: *const Schema) bool {
    return switch (schema.kind) {
        .list => schema.child.?.kind != .u8,
        .dict => true,
        .opt => owns(schema.child.?),
        .structure => for (schema.fields) |field| {
            if (owns(field.schema)) break true;
        } else false,
        else => false,
    };
}

fn minWire(schema: *const Schema) usize {
    return switch (schema.kind) {
        .boolean, .i8, .u8 => 1,
        .i16, .u16 => 2,
        .i32, .u32, .f32 => 4,
        .i64, .u64, .int, .uint, .f64 => 8,
        .str, .bytes, .list, .dict => 4,
        .tensors => 64,
        .opt => 1,
        .structure => blk: {
            var sum: usize = 0;
            for (schema.fields) |field| sum += minWire(field.schema);
            break :blk sum;
        },
    };
}

fn width(kind: Kind) ?usize {
    return switch (kind) {
        .boolean, .i8, .u8 => 1,
        .i16, .u16 => 2,
        .i32, .u32, .f32 => 4,
        .i64, .u64, .int, .uint, .f64 => 8,
        else => null,
    };
}

fn zigScalar(kind: Kind) []const u8 {
    return switch (kind) {
        .i8 => "i8",
        .i16 => "i16",
        .i32 => "i32",
        .i64, .int => "i64",
        .u8 => "u8",
        .u16 => "u16",
        .u32 => "u32",
        .u64, .uint => "u64",
        .f32 => "f32",
        .f64 => "f64",
        else => "u8",
    };
}

fn ident(name: []const u8) bool {
    if (name.len == 0) return false;
    if (!std.ascii.isAlphabetic(name[0]) and name[0] != '_') return false;
    for (name[1..]) |c| if (!std.ascii.isAlphanumeric(c) and c != '_') return false;
    const words = [_][]const u8{ "align", "and", "anytype", "asm", "async", "await", "break", "catch", "comptime", "const", "continue", "defer", "else", "enum", "errdefer", "error", "export", "extern", "false", "fn", "for", "if", "inline", "noalias", "noinline", "nosuspend", "opaque", "or", "orelse", "packed", "pub", "resume", "return", "linksection", "struct", "suspend", "switch", "test", "threadlocal", "true", "try", "union", "unreachable", "usingnamespace", "var", "volatile", "while" };
    for (words) |word| if (std.mem.eql(u8, name, word)) return false;
    return true;
}
